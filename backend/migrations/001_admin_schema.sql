-- Initial admin schema. Apply through apply_dev.sql, not as individual statements.
-- Business publication checks and image authorization belong to the backend.
CREATE TABLE admin_accounts (
    id smallint PRIMARY KEY DEFAULT 1 CHECK (id = 1),
    username varchar(64) NOT NULL UNIQUE CHECK (username = btrim(username) AND username <> ''),
    password_hash text NOT NULL CHECK (btrim(password_hash) <> ''),
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE admin_sessions (
    token_hash bytea PRIMARY KEY CHECK (octet_length(token_hash) = 32),
    admin_id smallint NOT NULL REFERENCES admin_accounts(id) ON DELETE CASCADE,
    created_at timestamptz NOT NULL DEFAULT now(),
    expires_at timestamptz NOT NULL,
    revoked_at timestamptz,
    CONSTRAINT admin_sessions_expiry_check CHECK (expires_at > created_at)
);
CREATE INDEX admin_sessions_expires_at_idx ON admin_sessions(expires_at);

CREATE TABLE uploaded_files (
    id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    storage_key text NOT NULL UNIQUE CHECK (btrim(storage_key) <> ''),
    original_name text NOT NULL,
    media_type varchar(100) NOT NULL CHECK (btrim(media_type) <> ''),
    byte_size bigint NOT NULL CHECK (byte_size > 0),
    width integer NOT NULL CHECK (width > 0),
    height integer NOT NULL CHECK (height > 0),
    created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE projects (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name varchar(100) NOT NULL DEFAULT '',
    summary text NOT NULL DEFAULT '',
    tech_stack text[] NOT NULL DEFAULT ARRAY[]::text[],
    cover_file_id uuid REFERENCES uploaded_files(id) ON DELETE RESTRICT,
    demo_url text,
    source_url text,
    status varchar(16) NOT NULL DEFAULT 'draft' CHECK (status IN ('draft', 'published', 'archived')),
    sort_order integer NOT NULL DEFAULT 0 CHECK (sort_order >= 0),
    published_at timestamptz,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX projects_status_sort_idx ON projects(status, sort_order, id);
CREATE INDEX projects_cover_file_idx ON projects(cover_file_id) WHERE cover_file_id IS NOT NULL;

CREATE TABLE project_blocks (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id bigint NOT NULL REFERENCES projects(id) ON DELETE CASCADE,
    position integer NOT NULL CHECK (position >= 0),
    kind varchar(16) NOT NULL CHECK (kind IN ('text', 'image')),
    body text,
    file_id uuid REFERENCES uploaded_files(id) ON DELETE RESTRICT,
    caption text,
    CONSTRAINT project_blocks_content_check CHECK (
        (kind = 'text' AND body IS NOT NULL AND file_id IS NULL)
        OR (kind = 'image' AND file_id IS NOT NULL AND body IS NULL)
    ),
    CONSTRAINT project_blocks_project_position_key UNIQUE (project_id, position) DEFERRABLE INITIALLY IMMEDIATE
);
CREATE INDEX project_blocks_file_idx ON project_blocks(file_id) WHERE file_id IS NOT NULL;

CREATE TABLE project_screenshots (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id bigint NOT NULL REFERENCES projects(id) ON DELETE CASCADE,
    file_id uuid NOT NULL REFERENCES uploaded_files(id) ON DELETE RESTRICT,
    position integer NOT NULL CHECK (position >= 0),
    caption text,
    CONSTRAINT project_screenshots_project_position_key UNIQUE (project_id, position) DEFERRABLE INITIALLY IMMEDIATE,
    CONSTRAINT project_screenshots_project_file_key UNIQUE (project_id, file_id)
);
CREATE INDEX project_screenshots_file_idx ON project_screenshots(file_id);

CREATE TABLE site_profile (
    id smallint PRIMARY KEY DEFAULT 1 CHECK (id = 1),
    name varchar(100) NOT NULL,
    title text NOT NULL,
    introduction text NOT NULL,
    avatar_file_id uuid REFERENCES uploaded_files(id) ON DELETE RESTRICT,
    skills text[] NOT NULL DEFAULT ARRAY[]::text[],
    contacts jsonb NOT NULL DEFAULT '[]'::jsonb CHECK (jsonb_typeof(contacts) = 'array'),
    social_links jsonb NOT NULL DEFAULT '[]'::jsonb CHECK (jsonb_typeof(social_links) = 'array'),
    updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE tool_settings (
    tool_key varchar(64) PRIMARY KEY,
    placement varchar(16) NOT NULL CHECK (placement IN ('grid', 'floating')),
    is_visible boolean NOT NULL DEFAULT true,
    sort_order integer NOT NULL DEFAULT 0 CHECK (sort_order >= 0),
    updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE site_daily_visitors (
    visit_date date NOT NULL,
    visitor_id uuid NOT NULL,
    PRIMARY KEY (visit_date, visitor_id)
);

CREATE TABLE project_daily_visitors (
    project_id bigint NOT NULL REFERENCES projects(id) ON DELETE RESTRICT,
    visit_date date NOT NULL,
    visitor_id uuid NOT NULL,
    PRIMARY KEY (project_id, visit_date, visitor_id)
);
CREATE INDEX project_daily_visitors_date_idx ON project_daily_visitors(visit_date, project_id, visitor_id);
